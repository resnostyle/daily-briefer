#!/usr/bin/env python3
"""Fetch Hacker News top 10 and send to Telegram."""
import os
import sys

# Allow importing src when run from repo root or from Docker (PYTHONPATH=/app)
_script_dir = os.path.dirname(os.path.abspath(__file__))
_repo_root = os.path.dirname(_script_dir)
if _repo_root not in sys.path:
    sys.path.insert(0, _repo_root)

import requests

from src.telegram import send_message

HN_TOP_URL = "https://hacker-news.firebaseio.com/v0/topstories.json"
HN_ITEM_URL = "https://hacker-news.firebaseio.com/v0/item/{id}.json"
HN_ITEM_PAGE = "https://news.ycombinator.com/item?id={id}"
MAX_STORIES = 10


def _escape_markdown(text: str) -> str:
    """Escape characters that break Telegram Markdown."""
    if not text:
        return ""
    for char in ("\\", "_", "*", "`", "["):
        text = text.replace(char, "\\" + char)
    return text


def _fetch_top_ids() -> list[int]:
    r = requests.get(HN_TOP_URL, timeout=15)
    r.raise_for_status()
    return r.json()


def _fetch_item(item_id: int) -> dict | None:
    r = requests.get(HN_ITEM_URL.format(id=item_id), timeout=10)
    r.raise_for_status()
    return r.json()


def _fetch_top_stories() -> list[dict]:
    ids = _fetch_top_ids()
    stories = []
    for item_id in ids:
        if len(stories) >= MAX_STORIES:
            break
        item = _fetch_item(item_id)
        if not item or item.get("type") != "story" or item.get("deleted") or item.get("dead"):
            continue
        title = item.get("title") or ""
        if not title:
            continue
        url = item.get("url") or HN_ITEM_PAGE.format(id=item_id)
        score = item.get("score", 0)
        by = item.get("by", "?")
        stories.append({"title": title, "url": url, "score": score, "by": by})
    return stories


def build_message(stories: list[dict]) -> str:
    """Build Telegram Markdown message."""
    lines = ["*Hacker News — Top 10*", ""]
    for i, s in enumerate(stories, 1):
        title = _escape_markdown(s["title"])
        if len(title) > 200:
            title = title[:197] + "..."
        url = s["url"]
        score = s["score"]
        by = _escape_markdown(s["by"])
        lines.append(f"{i}. [{title}]({url})")
        lines.append(f"   {score} points · by {by}")
        lines.append("")
    lines.append("_Generated by daily-briefing._")
    return "\n".join(lines).strip()


def main() -> int:
    try:
        stories = _fetch_top_stories()
    except Exception as e:
        print(f"Hacker News API error: {e}", file=sys.stderr)
        fallback = "Could not fetch Hacker News top stories."
        if send_message(fallback, parse_mode=None):
            return 0
        return 1
    if not stories:
        fallback = "Could not load any top stories."
        if send_message(fallback, parse_mode=None):
            return 0
        return 1
    text = build_message(stories)
    if send_message(text):
        return 0
    return 1


if __name__ == "__main__":
    sys.exit(main())
