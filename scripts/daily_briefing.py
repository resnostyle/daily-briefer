#!/usr/bin/env python3
"""Build and send the daily briefing to Telegram."""
import os
import sys
from datetime import date

# Allow importing src when run from repo root or from Docker (PYTHONPATH=/app)
_script_dir = os.path.dirname(os.path.abspath(__file__))
_repo_root = os.path.dirname(_script_dir)
if _repo_root not in sys.path:
    sys.path.insert(0, _repo_root)

from src.telegram import send_message


def build_briefing() -> str:
    """Assemble the daily briefing text (placeholder content)."""
    today = date.today().strftime("%A, %B %d, %Y")
    return f"""*Daily Briefing — {today}*

*Weather*
— Placeholder: add your weather source later.

*Headlines*
— Placeholder: add RSS or news API later.

*Reminders*
— Placeholder: add calendar or tasks later.

_Generated by daily-briefing._"""


def main() -> int:
    text = build_briefing()
    if send_message(text):
        return 0
    return 1


if __name__ == "__main__":
    sys.exit(main())
