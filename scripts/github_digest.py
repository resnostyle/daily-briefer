#!/usr/bin/env python3
"""Fetch GitHub trending (top 10) and send digest to Telegram."""
import os
import sys

# Allow importing src when run from repo root or from Docker (PYTHONPATH=/app)
_script_dir = os.path.dirname(os.path.abspath(__file__))
_repo_root = os.path.dirname(_script_dir)
if _repo_root not in sys.path:
    sys.path.insert(0, _repo_root)

import requests
from bs4 import BeautifulSoup

from src.telegram import send_message

GITHUB_TRENDING_URL = "https://github.com/trending?since=daily"
USER_AGENT = "daily-briefing/1.0 (https://github.com)"
MAX_REPOS = 10


def _escape_markdown(text: str) -> str:
    """Escape characters that break Telegram Markdown."""
    if not text:
        return ""
    for char in ("\\", "_", "*", "`", "["):
        text = text.replace(char, "\\" + char)
    return text


def _fetch_trending() -> str:
    r = requests.get(
        GITHUB_TRENDING_URL,
        headers={"User-Agent": USER_AGENT},
        timeout=30,
    )
    r.raise_for_status()
    return r.text


def _parse_trending(html: str) -> list[dict]:
    """Extract top repos from trending page. Returns list of dicts with owner, repo, desc, lang, stars_today."""
    soup = BeautifulSoup(html, "html.parser")
    # GitHub trending uses article.Box-row per repo
    rows = soup.select("article.Box-row")
    repos = []
    seen = set()
    for row in rows:
        if len(repos) >= MAX_REPOS:
            break
        # Link to repo: first link that looks like /owner/repo (no extra path)
        link = row.select_one('a[href^="/"][href*="/"]')
        if not link:
            continue
        href = link.get("href", "").strip("/")
        parts = href.split("/")
        if len(parts) != 2 or not parts[0] or not parts[1]:
            continue
        owner, repo_name = parts
        key = (owner, repo_name)
        if key in seen:
            continue
        seen.add(key)

        desc_el = row.select_one("p")
        desc = (desc_el.get_text(strip=True) if desc_el else "") or ""
        # Truncate long descriptions
        if len(desc) > 120:
            desc = desc[:117] + "..."

        lang_el = row.select_one('[itemprop="programmingLanguage"]')
        lang = (lang_el.get_text(strip=True) if lang_el else "") or "—"

        # "X stars today" or "X.Yk stars today"
        stars_today = ""
        for span in row.select("span"):
            t = span.get_text(strip=True)
            if "stars today" in t or "star today" in t:
                stars_today = t
                break

        repos.append({
            "owner": owner,
            "repo": repo_name,
            "desc": desc,
            "lang": lang,
            "stars_today": stars_today or "—",
        })
    return repos


def build_digest(repos: list[dict]) -> str:
    """Build Telegram Markdown message."""
    lines = ["*GitHub Trending — Top 10 (today)*", ""]
    for i, r in enumerate(repos, 1):
        full_name = f"{r['owner']}/{r['repo']}"
        url = f"https://github.com/{r['owner']}/{r['repo']}"
        # Use escaped text only where we inject user content; link and structure are safe
        desc = _escape_markdown(r["desc"]) if r["desc"] else "—"
        lang = _escape_markdown(r["lang"])
        stars = _escape_markdown(r["stars_today"])
        lines.append(f"{i}. [{full_name}]({url})")
        lines.append(f"   {desc} · {lang} · {stars}")
        lines.append("")
    lines.append("_Generated by daily-briefing._")
    return "\n".join(lines).strip()


def main() -> int:
    try:
        html = _fetch_trending()
        repos = _parse_trending(html)
    except Exception as e:
        print(f"GitHub trending fetch/parse error: {e}", file=sys.stderr)
        fallback = "Could not fetch trending repos."
        if send_message(fallback, parse_mode=None):
            return 0
        return 1
    if not repos:
        fallback = "Could not parse any trending repos."
        if send_message(fallback, parse_mode=None):
            return 0
        return 1
    text = build_digest(repos)
    if send_message(text):
        return 0
    return 1


if __name__ == "__main__":
    sys.exit(main())
